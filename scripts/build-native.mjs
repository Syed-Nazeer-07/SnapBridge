import './native-config.mjs';
import { spawnSync } from 'node:child_process';
import { cp } from 'node:fs/promises';
const arch=process.env.SNAPFLOW_ARCH||'x64';
if(!['x64','arm64'].includes(arch))throw new Error('Unsupported native host architecture.');
const windows=process.platform==='win32'||process.argv.includes('--windows');
const runtime=windows?`win-${arch}`:'linux-x64';
const directory=`dist/native-host/${runtime}`;
const result=spawnSync(process.env.SNAPFLOW_DOTNET||'dotnet',['publish','native-host/SnapFlow.NativeHost.csproj','-c','Release','-r',runtime,'--self-contained',windows?'true':'false','-o',directory,...(windows?[]:['-p:PublishSingleFile=false'])],{stdio:'inherit'});
if(result.error)throw result.error;if(result.status!==0)process.exit(result.status||1);
await cp('dist/native-config.json',`${directory}/native-config.json`);
